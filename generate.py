def luminance(hex_color):
    """Calculate relative luminance of a color (0-1)."""
    r, g, b = hex_to_rgb(hex_color)
    return (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255


def for_light_bg(hex_color, max_lum=0.38):
    """Darken a color so it's readable on a light background.

    Preserves hue by scaling RGB proportionally, targeting max_lum luminance.
    """
    r, g, b = hex_to_rgb(hex_color)
    lum = (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255
    if lum <= max_lum:
        return hex_color
    factor = (max_lum / max(lum, 0.01)) ** 0.75
    return rgb_to_hex(
        max(0, min(255, r * factor)),
        max(0, min(255, g * factor)),
        max(0, min(255, b * factor)),
    )


def blend_to_white(hex_color, factor=0.80):
    """Blend a color toward white, preserving its hue character.

    factor=0 returns the original color, factor=1 returns pure white.
    """
    r, g, b = hex_to_rgb(hex_color)
    r = r + (255 - r) * factor
    g = g + (255 - g) * factor
    b = b + (255 - b) * factor
    return rgb_to_hex(r, g, b)


def derive_light_artist(dark):
    """Derive a light theme variant from a dark theme definition."""
    # Use the dark theme's text color (the lightest palette color) to derive
    # tinted backgrounds. Each artist gets a distinctly warm/cool/golden bg.
    palette_light = dark["text"]

    # Backgrounds: blend the lightest palette color toward white
    bg = blend_to_white(palette_light, 0.80)
    editor_bg = blend_to_white(palette_light, 0.86)
    surface = blend_to_white(palette_light, 0.74)
    elevated = blend_to_white(palette_light, 0.90)

    # Text: dark, from the palette
    text = for_light_bg(dark["text"], 0.15)
    text_muted = for_light_bg(dark["text_muted"], 0.40)

    # Borders: light gray, tinted
    border = darken(bg, 0.12)
    border_focused = for_light_bg(dark["border_focused"], 0.40)

    # Syntax: darken all dark-theme syntax colors for light bg readability
    comment = for_light_bg(dark["comment"], 0.42)
    keyword = for_light_bg(dark["keyword"], 0.35)
    string = for_light_bg(dark["string"], 0.38)
    function = for_light_bg(dark["function"], 0.32)
    type_ = for_light_bg(dark["type"], 0.38)
    variable = for_light_bg(dark["variable"], 0.35)
    number = for_light_bg(dark["number"], 0.36)
    constant = for_light_bg(dark["constant"], 0.38)
    operator = for_light_bg(dark["operator"], 0.40)
