def build_family(artist):
    """Build a theme family JSON with both dark and light variants."""
    dark_theme = build_theme(artist)
    light_artist = derive_light_artist(artist)
    light_theme = build_theme(light_artist)
    return {
        "$schema": "https://zed.dev/schema/themes/v0.2.0.json",
        "name": f"Palette Masters: {artist['name']}",
        "author": "Palette Inspiration (paletteinspiration.com)",
        "themes": [dark_theme, light_theme],
    }


def main():
    os.makedirs(THEMES_DIR, exist_ok=True)

    count = 0
    for artist in ARTISTS:
        family = build_family(artist)
        filename = f"palette-masters-{artist['id']}.json"
        filepath = os.path.join(THEMES_DIR, filename)

        with open(filepath, "w") as f:
            json.dump(family, f, indent=2)

        dark_name = family["themes"][0]["name"]
        light_name = family["themes"][1]["name"]
        print(f"Created: {filepath}")
        print(f"  Dark:  {dark_name}")
        print(f"  Light: {light_name}")
        count += 1

    print(f"\nGenerated {count} theme files ({count * 2} themes) in {THEMES_DIR}")
    print("\nTo use a theme in Zed:")
    print("  1. Open Zed")
    print("  2. Press Ctrl+K Ctrl+T (or Cmd+K Cmd+T on macOS)")
    print("  3. Search for 'Palette Masters' or the artist name")


if __name__ == "__main__":
    main()
