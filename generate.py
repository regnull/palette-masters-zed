def hex_to_rgb(hex_color):
    h = hex_color.lstrip("#")
    return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))

def rgb_to_hex(r, g, b):
    return f"#{int(r):02x}{int(g):02x}{int(b):02x}"

def lighten(hex_color, amount=0.2):
    r, g, b = hex_to_rgb(hex_color)
    r = min(255, r + (255 - r) * amount)
    g = min(255, g + (255 - g) * amount)
    b = min(255, b + (255 - b) * amount)
    return rgb_to_hex(r, g, b)

def darken(hex_color, amount=0.3):
    r, g, b = hex_to_rgb(hex_color)
    r = max(0, r * (1 - amount))
    g = max(0, g * (1 - amount))
    b = max(0, b * (1 - amount))
    return rgb_to_hex(r, g, b)

def with_alpha(hex_color, alpha):
    """Return hex color with alpha (0-255)."""
    return f"{hex_color}{int(alpha):02x}"

